import { beforeEach, describe, expect, it, vi } from 'vitest'
import { useScoreParseDrawer } from './useScoreParseDrawer.js'
import { scoreParseApi } from '@/api/modules/scoreParse.js'
vi.mock('@/api/modules/scoreParse.js', () => ({ scoreParseApi: Object.fromEntries(['getItems', 'getResults', 'getLatestExtraction', 'getExtraction', 'activateExtraction', 'getReview', 'triggerScoring', 'triggerParse', 'getParseStatus'].map(k => [k, vi.fn()])) }))
vi.mock('element-plus', () => ({ ElMessage: { success: vi.fn(), error: vi.fn(), warning: vi.fn(), info: vi.fn() } }))
const active = (fingerprint = 'v1') => ({ versionId: 1, taskId: 'old', parseTaskId: 1, fingerprint, activatedAt: '2026-09-20T12:00:00', hasManualEdits: false })
const view = (fingerprint = 'v1') => ({ taskId: 'latest', parseTaskId: 2, taskStatus: 'COMPLETED', payloadVersion: 1, snapshotStatus: 'FROZEN', extractedAt: '2026-09-27T12:00:00', schemes: [{ schemeId: 's', title: '评分方案', extractedCount: 13, extractedKnownTotal: 100, extractedTotalComplete: true, computableCount: 13, computableTotal: 100, activeCount: 0, activeTotal: 0, declaredTotal: 200, declaredTotalStatus: 'KNOWN' }], items: [{ itemId: 'one', schemeId: 's', computable: true, effectiveMaximum: 100 }], active: active(fingerprint), adoption: { status: 'NOT_ADOPTED', adoptedItemIds: [], remainingItemIds: ['one'] } })
const items = (id = 1) => ({ data: { items: [{ id, dim: '当前规则', detail: '当前原文', weight: 100, scoreType: 'OBJECTIVE' }], parseTime: '2026-09-20T12:00:00', meta: { lastParseStatus: 'COMPLETED' } } })
const failure = (status, msg) => ({ response: { status, data: { msg } } })
describe('extraction and active bundle', () => {
  beforeEach(() => {
    vi.resetAllMocks()
    scoreParseApi.getLatestExtraction.mockResolvedValue({ data: view() })
    scoreParseApi.getExtraction.mockResolvedValue({ data: { ...view(), taskId: 'old', schemes: [{ ...view().schemes[0], activeCount: 1, declaredTotal: 100 }] } })
    scoreParseApi.getItems.mockResolvedValue(items())
    scoreParseApi.getResults.mockResolvedValue({ data: { results: [] } })
  })
  const open = async () => { const d = useScoreParseDrawer({ projectId: 9 }, vi.fn()); await d.open({ autoParse: false, autoScore: false }); return d }
  it('keeps latest totals separate from old active source declaration and time', async () => {
    const d = await open()
    expect(d.latestExtraction?.value?.taskId).toBe('latest')
    expect(d.activeDeclaredTotal?.value).toBe(100)
    expect(d.totalWeight.value).toBe(100)
    expect(d.parseTime.value).toContain('20')
  })
  it('retries a read race before publishing items paired with another active fingerprint', async () => {
    let release
    const gate = new Promise(resolve => { release = resolve })
    scoreParseApi.getItems.mockImplementationOnce(() => gate).mockResolvedValue(items(2))
    scoreParseApi.getLatestExtraction.mockResolvedValueOnce({ data: view('v1') }).mockResolvedValue({ data: view('v2') })
    scoreParseApi.getExtraction.mockResolvedValue({ data: { ...view('v2'), taskId: 'old' } })
    const d = useScoreParseDrawer({ projectId: 9 }, vi.fn())
    const pending = d.open({ autoParse: false })
    await vi.waitFor(() => expect(scoreParseApi.getItems).toHaveBeenCalled())
    release(items(1)); await pending
    expect(d.scoreItems.value[0].id).toBe(2)
    expect(d.latestExtraction?.value.active.fingerprint).toBe('v2')
  })
  it('posts full replacement and original CAS once; conflict requires explicit refresh', async () => {
    const d = await open()
    scoreParseApi.activateExtraction.mockRejectedValue(failure(409, 'ACTIVE_FINGERPRINT_CONFLICT'))
    await d.activateExtraction({ schemeId: 's', selectedItemIds: ['one'], reason: '逐项核对' })
    expect(scoreParseApi.activateExtraction).toHaveBeenCalledWith(9, 'latest', { schemeId: 's', selectedItemIds: ['one'], reason: '逐项核对', expectedActiveFingerprint: 'v1' })
    expect(scoreParseApi.activateExtraction).toHaveBeenCalledTimes(1)
    expect(d.extractionWarning.value).toContain('刷新')
    expect(d.activationBlocked.value).toBe(true)
    expect(scoreParseApi.triggerScoring).not.toHaveBeenCalled()
    expect(scoreParseApi.triggerParse).not.toHaveBeenCalled()
  })
  it('does not treat 403 or 500 as feature disabled', async () => {
    for (const status of [403, 500]) {
      scoreParseApi.getLatestExtraction.mockRejectedValue(failure(status, '读取失败'))
      const d = await open()
      expect(d.error.value).toBeTruthy()
      expect(d.activationBlocked?.value).toBe(true)
    }
  })
  it('feature off keeps historical scores visible but not current/completed or totaled', async () => {
    scoreParseApi.getLatestExtraction.mockRejectedValue(failure(409, 'EXTRACTION_FEATURE_DISABLED'))
    scoreParseApi.getResults.mockResolvedValue({ data: { results: [{ scoreItemId: 1, actualScore: 80, status: 'PENDING', reuseKind: 'LEGACY_UNVERIFIED', evidence: '历史依据' }] } })
    const d = await open()
    expect(d.error.value).toBe('')
    expect(d.scoreResults.value['id:1'].actualScore).toBe(80)
    expect(d.actualTotalScore.value).toBeNull()
    expect(d.scored.value).toBe(false)
    expect(d.hasHistoricalResults?.value).toBe(true)
    expect(d.currentStage.value).toBe(2)
  })
})

describe('extraction refresh safety', () => {
  beforeEach(() => {
    vi.resetAllMocks()
    scoreParseApi.getLatestExtraction.mockResolvedValue({ data: view() })
    scoreParseApi.getExtraction.mockResolvedValue({ data: { ...view(), taskId: 'old', schemes: [{ ...view().schemes[0], activeCount: 1, declaredTotal: 100 }] } })
    scoreParseApi.getItems.mockResolvedValue(items())
    scoreParseApi.getResults.mockResolvedValue({ data: { results: [] } })
  })
  it('keeps the last coherent bundle and blocks writes when repeated concurrent activation cannot stabilize', async () => {
    const d = useScoreParseDrawer({ projectId: 9 }, vi.fn())
    await d.open({ autoParse: false })
    let count = 0
    scoreParseApi.getLatestExtraction.mockImplementation(async () => ({ data: view('changed-' + ++count) }))
    scoreParseApi.getItems.mockResolvedValue(items(88))
    await d.refreshExtraction()
    expect(d.scoreItems.value[0].id).toBe(1)
    expect(d.latestExtraction.value.active.fingerprint).toBe('v1')
    expect(d.activationBlocked.value).toBe(true)
    expect(d.extractionWarning.value).toContain('刷新')
    expect(count).toBe(6)
  })
  it('successful activation refresh cannot trigger scoring or parsing', async () => {
    const d = useScoreParseDrawer({ projectId: 9 }, vi.fn())
    await d.open({ autoParse: false })
    scoreParseApi.activateExtraction.mockResolvedValue({ data: view() })
    scoreParseApi.getItems.mockResolvedValue({ data: { items: [], meta: { bidFileName: '投标书.pdf' } } })
    await d.activateExtraction({ schemeId: 's', selectedItemIds: ['one'], reason: '核对' })
    expect(scoreParseApi.triggerScoring).not.toHaveBeenCalled()
    expect(scoreParseApi.triggerParse).not.toHaveBeenCalled()
    expect(d.scoreItems.value).toEqual([])
  })
  it('legacy payload keeps active items and explicitly blocks activation and automatic parsing', async () => {
    scoreParseApi.getLatestExtraction.mockResolvedValue({ data: { ...view(), payloadVersion: 0, snapshotStatus: 'LEGACY_UNKNOWN' } })
    const d = useScoreParseDrawer({ projectId: 9 }, vi.fn())
    await d.open()
    expect(d.scoreItems.value[0].id).toBe(1)
    expect(d.activationBlocked.value).toBe(true)
    expect(scoreParseApi.triggerParse).not.toHaveBeenCalled()
  })
  it('skipped scoring refreshes the coherent current active bundle', async () => {
    const d = useScoreParseDrawer({ projectId: 9 }, vi.fn())
    await d.open({ stage: 2, autoParse: false })
    scoreParseApi.triggerScoring.mockResolvedValue({ data: { outcome: 'SKIPPED', hint: '已评分' } })
    scoreParseApi.getItems.mockResolvedValue(items(2))
    await d.runScoring()
    expect(d.scoreItems.value[0].id).toBe(2)
  })
  it('failed manual reparse refreshes the latest failed snapshot without replacing active rules', async () => {
    const d = useScoreParseDrawer({ projectId: 9 }, vi.fn())
    await d.open({ autoParse: false })
    scoreParseApi.triggerParse.mockResolvedValue({ data: { taskId: 'failed', status: 'PENDING' } })
    scoreParseApi.getParseStatus.mockResolvedValue({ data: { taskId: 'failed', status: 'FAILED', errorMessage: '文件失败' } })
    scoreParseApi.getLatestExtraction.mockResolvedValue({ data: { ...view(), taskId: 'failed', taskStatus: 'FAILED' } })
    await d.reparse()
    expect(d.latestExtraction.value.taskId).toBe('failed')
    expect(d.scoreItems.value[0].id).toBe(1)
    expect(d.activationBlocked.value).toBe(true)
  })
  it('initial snapshot server error still allows active rules to be inspected with no activation', async () => {
    scoreParseApi.getLatestExtraction.mockRejectedValue(failure(500, '快照服务暂不可用'))
    const d = useScoreParseDrawer({ projectId: 9 }, vi.fn())
    await d.open({ autoParse: false })
    expect(d.scoreItems.value[0]?.id).toBe(1)
    expect(d.error.value).toContain('快照服务暂不可用')
    expect(d.activationBlocked.value).toBe(true)
  })
})

describe('historical source read failure', () => {
  beforeEach(() => {
    vi.resetAllMocks()
    scoreParseApi.getLatestExtraction.mockResolvedValue({ data: view() })
    scoreParseApi.getItems.mockResolvedValue(items())
    scoreParseApi.getResults.mockResolvedValue({ data: { results: [{ scoreItemId: 1, actualScore: 80, status: 'OK' }] } })
    scoreParseApi.getExtraction.mockRejectedValue(failure(500, '旧来源快照读取失败'))
  })
  it('cold opens with consistent active rules and results while source error stays visible and writes blocked', async () => {
    const d = useScoreParseDrawer({ projectId: 9 }, vi.fn())
    await d.open({ autoScore: true })
    expect(d.scoreItems.value[0]?.id).toBe(1)
    expect(d.scoreResults.value['id:1']?.actualScore).toBe(80)
    expect(d.latestExtraction.value?.active.fingerprint).toBe('v1')
    expect(d.error.value).toContain('旧来源快照读取失败')
    expect(d.activeDeclaredTotal.value).toBeNull()
    expect(d.activationBlocked.value).toBe(true)
    expect(scoreParseApi.getLatestExtraction).toHaveBeenCalledTimes(2)
    expect(scoreParseApi.triggerParse).not.toHaveBeenCalled()
    expect(scoreParseApi.triggerScoring).not.toHaveBeenCalled()
  })
  it('refreshes already open items safely, clears stale declaration, and recovers after source service returns', async () => {
    const source = { data: { ...view(), taskId: 'old', schemes: [{ ...view().schemes[0], activeCount: 1, declaredTotal: 100 }] } }
    scoreParseApi.getExtraction.mockResolvedValueOnce(source)
    const d = useScoreParseDrawer({ projectId: 9 }, vi.fn())
    await d.open({ autoParse: false })
    expect(d.activeDeclaredTotal.value).toBe(100)
    scoreParseApi.getItems.mockResolvedValue(items(2))
    scoreParseApi.getResults.mockResolvedValue({ data: { results: [{ scoreItemId: 2, actualScore: 90, status: 'OK' }] } })
    await d.refreshExtraction()
    expect(d.scoreItems.value[0]?.id).toBe(2)
    expect(d.scoreResults.value['id:2']?.actualScore).toBe(90)
    expect(d.activeDeclaredTotal.value).toBeNull()
    expect(d.error.value).toContain('旧来源快照读取失败')
    expect(d.activationBlocked.value).toBe(true)
    scoreParseApi.getExtraction.mockResolvedValue(source)
    await d.open({ autoScore: false, autoParse: false })
    expect(d.error.value).toBe('')
    expect(d.activeDeclaredTotal.value).toBe(100)
    expect(d.activationBlocked.value).toBe(false)
    expect(scoreParseApi.triggerParse).not.toHaveBeenCalled()
    expect(scoreParseApi.triggerScoring).not.toHaveBeenCalled()
  })
  it('retries changed fingerprints during source failure before exposing the safe replacement bundle', async () => {
    let release
    const deferred = new Promise(resolve => { release = resolve })
    scoreParseApi.getLatestExtraction.mockResolvedValueOnce({ data: view('v1') }).mockImplementationOnce(() => deferred).mockResolvedValue({ data: view('v2') })
    scoreParseApi.getItems.mockResolvedValueOnce(items(1)).mockResolvedValue(items(2))
    scoreParseApi.getResults.mockResolvedValueOnce({ data: { results: [{ scoreItemId: 1, actualScore: 80, status: 'OK' }] } }).mockResolvedValue({ data: { results: [{ scoreItemId: 2, actualScore: 90, status: 'OK' }] } })
    const d = useScoreParseDrawer({ projectId: 9 }, vi.fn())
    const pending = d.open({ autoScore: true })
    await vi.waitFor(() => expect(scoreParseApi.getLatestExtraction).toHaveBeenCalledTimes(2))
    expect(d.scoreItems.value).toEqual([])
    release({ data: view('v2') }); await pending
    expect(d.scoreItems.value[0]?.id).toBe(2)
    expect(d.scoreResults.value['id:1']).toBeUndefined()
    expect(d.scoreResults.value['id:2']?.actualScore).toBe(90)
    expect(d.latestExtraction.value?.active.fingerprint).toBe('v2')
    expect(d.activationBlocked.value).toBe(true)
    expect(d.error.value).toContain('旧来源快照读取失败')
    expect(scoreParseApi.triggerParse).not.toHaveBeenCalled()
    expect(scoreParseApi.triggerScoring).not.toHaveBeenCalled()
  })
  it('does not degrade a historical source permission rejection into readable active items', async () => {
    scoreParseApi.getExtraction.mockRejectedValue(failure(403, '无权访问历史来源'))
    const d = useScoreParseDrawer({ projectId: 9 }, vi.fn())
    await d.open({ autoScore: true })
    expect(d.scoreItems.value).toEqual([])
    expect(d.latestExtraction.value).toBeNull()
    expect(d.error.value).toContain('无权访问历史来源')
    expect(d.activationBlocked.value).toBe(true)
    expect(scoreParseApi.triggerParse).not.toHaveBeenCalled()
    expect(scoreParseApi.triggerScoring).not.toHaveBeenCalled()
  })
})
