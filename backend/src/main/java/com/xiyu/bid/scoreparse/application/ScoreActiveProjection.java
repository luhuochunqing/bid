/** Boundary mapper preserves original evidence and hashes every rule-affecting field. */
final class ScoreActiveProjection {
    private ScoreActiveProjection() {}
    static ScoreItem item(Long projectId,Long taskId,Long versionId,int index,ExtractedScoreItem i,ScoreExtractionCodec codec) {
        var f=i.fact();
        return ScoreItem.builder().projectId(projectId).parseTaskId(taskId).activeVersionId(versionId)
                .sourceFactId(i.factId()).itemIndex(index).code(ScoreCodeSanitizer.clean(f.code()).isBlank()?"item-"+index:ScoreCodeSanitizer.clean(f.code()))
                .dim(i.name()).detail(i.ruleText()).weight(i.effectiveMaximum()).scoreType(i.scoreType())
                .deliverableType(ScoreItemClassificationPolicy.classifyDeliverableType(
                        i.name(), i.ruleText(), null))
                .scoringMode(ScoreItemClassificationPolicy.classifyScoringMode(
                        i.ruleText(), i.scoreType(), null))
                .statusStage1("PENDING").sourceText(f.sourceText()).sourceCellIds(codec.encode(f.sourceCellIds()))
                .weightEvidence(f.weightEvidence()==null?null:codec.encode(f.weightEvidence())).extractionMethod(f.extractionMethod())
                .confidence(i.confidence()).validationStatus(i.validationStatus())
                .ruleFingerprint(ScoreVersionFingerprint.hash(codec.encode(Arrays.asList(i.itemId(),i.factId(),i.schemeId(),i.fileId(),i.name(),i.category(),i.ruleText(),i.materialRequirements(),i.rawMaximum(),i.schemeRatio(),i.effectiveMaximum(),i.scoreType(),i.parentItemId(),i.aggregation(),f.sourceText(),f.sourceCellIds(),f.sourceMetadata().sourceSpans())))).build();
    }
    static String fingerprint(List<ScoreItem> items,ScoreExtractionCodec codec) {
        List<List<Object>> canonical=new ArrayList<>();
        for(var i:items) canonical.add(Arrays.asList(i.getId(),i.getParseTaskId(),i.getActiveVersionId(),i.getSourceFactId(),
                i.getItemIndex(),i.getCode(),i.getDim(),i.getDetail(),i.getWeight()==null?null:i.getWeight().stripTrailingZeros().toPlainString(),
                i.getScoreType(),i.getContextNote(),i.getSourceText(),codec.canonicalStoredJson(i.getSourceCellIds()),codec.canonicalStoredJson(i.getWeightEvidence()),i.getParentScoreItemId(),i.getRuleFingerprint()));
        return ScoreVersionFingerprint.hash(codec.encode(canonical));
    }
}
